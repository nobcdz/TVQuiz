module.exports = function addPracticeSets(add) {
    const skills = [
        [
            ['20以内加法', (a, b) => [`小盒装了 ${a} 颗珠子，大盒装了 ${b} 颗，两盒一共有几颗？`, a + b, '把两盒的数量相加。']],
            ['20以内减法', (a, b) => [`纸上画了 ${a + b} 个圆，涂掉 ${b} 个，没涂掉的有几个？`, a, '总数减去涂掉的数量。']],
            ['比较多少', (a, b) => [`左边有 ${a} 块积木，右边有 ${a + b} 块。右边多几块？`, b, '用右边的块数减去左边的块数。']],
            ['补足数量', (a, b) => [`要摆 ${a + b} 把椅子，已经摆好 ${a} 把，还要摆几把？`, b, '用需要的总数减去已经摆好的数量。']]
        ],
        [
            ['乘法应用', (a, b) => [`有 ${a} 排座位，每排 ${b} 个，共有多少个座位？`, a * b, '排数乘每排座位数。']],
            ['平均分', (a, b) => [`${a * b} 张卡片平均装入 ${a} 个袋子，每袋有几张？`, b, '总张数除以袋数。']],
            ['两位数加法', (a, b) => [`上午卖了 ${a + 20} 个面包，下午卖了 ${b + 30} 个，共卖多少个？`, a + b + 50, '把上午和下午卖出的数量相加。']],
            ['人民币计算', (a, b) => [`买一本 ${a + 10} 元的书和一把 ${b} 元的尺，付 30 元，应找回多少元？`, 20 - a - b, '先求两件物品的总价，再从 30 元中减去。']]
        ],
        [
            ['面积', (a, b) => [`长方形花圃长 ${a + 12} 米、宽 ${b} 米，面积是多少平方米？`, (a + 12) * b, '长方形面积等于长乘宽。']],
            ['周长', (a, b) => [`给长 ${a + 15} 厘米、宽 ${b} 厘米的照片围一圈边框，边框长多少厘米？`, 2 * (a + 15 + b), '把长和宽相加，再乘 2。']],
            ['经过时间', (a, b) => [`比赛 10:${10 + a} 开始，10:${30 + b} 结束，持续多少分钟？`, 20 + b - a, '同一小时内，用结束的分钟数减去开始的分钟数。']],
            ['质量换算', (a, b) => [`${a} 千克 ${b * 50} 克等于多少克？`, a * 1000 + b * 50, '每千克等于 1000 克，再加上剩余的克数。']]
        ],
        [
            ['小数加法', (a, b) => [`两根彩带分别长 ${a}.6 米和 ${b}.4 米，共长多少米？`, a + b + 1, '对齐小数点，0.6 加 0.4 得 1。']],
            ['三角形内角和', (a, b) => [`三角形的两个内角是 ${40 + a}° 和 ${60 + b}°，第三个内角是多少度？`, 80 - a - b, '用 180° 减去两个已知内角。']],
            ['乘法分配律', (a, b) => [`用简便方法计算 ${a + 10} × (${b} + 20)，结果是多少？`, (a + 10) * (b + 20), '让括号外的数分别乘括号里的两项，再相加。']],
            ['数据汇总', (a, b) => [`三组收集了 ${a + 12}、${b + 10}、${a + b} 张卡片，共多少张？`, 2 * (a + b) + 22, '把三组的数量相加。']]
        ],
        [
            ['分数加法', (a, b) => [`${a}/30 与 ${b + 10}/30 相加，结果仍写成分母为 30 的分数，分子是多少？`, a + b + 10, '同分母分数相加，分母不变，分子相加。']],
            ['梯形面积', (a, b) => [`梯形上底 ${a} 厘米、下底 ${b + 15} 厘米、高 6 厘米，面积是多少平方厘米？`, 3 * (a + b + 15), '上底加下底，乘高后除以 2。']],
            ['体积应用', (a, b) => [`长方体盒子长 ${a + 10} 厘米、宽 ${b} 厘米、高 3 厘米，体积是多少立方厘米？`, 3 * (a + 10) * b, '长乘宽再乘高。']],
            ['简易方程', (a, b) => [`解方程 5x + ${b} = ${5 * a + b}，x 是多少？`, a, '等式两边同时减去常数项，再除以 5。']]
        ],
        [
            ['百分数应用', (a, b) => [`一件物品原价 ${a * 100} 元，降价 ${b * 5}%，少付多少元？`, a * b * 5, '原价乘降价百分率。']],
            ['按比分配', (a, b) => [`红珠与白珠的数量比是 2∶${b + 2}，合计 ${a * (b + 4)} 颗，白珠有多少颗？`, a * (b + 2), '先求一份的数量，再乘白珠所占份数。']],
            ['圆柱体积', (a, b) => [`圆柱底面积是 ${a + 25} 平方厘米，高 ${b + 6} 厘米，体积是多少立方厘米？`, (a + 25) * (b + 6), '底面积乘高。']],
            ['比例尺', (a, b) => [`比例尺 1∶${b * 1000} 的图上长 ${a} 厘米，实际是多少米？`, a * b * 10, '按比例换算成厘米，再除以 100 化为米。']]
        ],
        [
            ['有理数加法', (a, b) => [`计算 (−${a + 10}) + ${b}，结果是多少？`, b - a - 10, '异号相加，用较大的绝对值减去较小的，符号随绝对值较大的数。']],
            ['整式化简', (a, b) => [`化简 ${a + 12}x − ${b}x，x 的系数是多少？`, a + 12 - b, '同类项相减只改变系数。']],
            ['一元一次方程', (a, b) => [`解方程 ${b + 2}x − 7 = ${(b + 2) * a - 7}，x 是多少？`, a, '两边加 7，再除以 x 的系数。']],
            ['不等式', (a, b) => [`−${b}x < −${a * b} 的解是 x 大于哪个数？`, a, '两边除以同一个负数，不等号方向反转。']]
        ],
        [
            ['一次函数', (a, b) => [`一次函数 y = ${b}x + 16，在 x = ${a + 10} 时的函数值是多少？`, b * (a + 10) + 16, '代入 x，再按先乘后加的顺序求值。']],
            ['完全平方', (a, b) => [`展开 (${a + 1}x + ${b})²，x 项的系数是多少？`, 2 * (a + 1) * b, '中间项是两个式子的乘积再乘 2。']],
            ['勾股定理', (a, b) => [`直角三角形的直角边分别为 ${(a + 12) ** 2 - b ** 2} 和 ${2 * (a + 12) * b}，斜边长是多少？`, (a + 12) ** 2 + b ** 2, '两条直角边分别平方后相加，再求算术平方根。']],
            ['统计平均数', (a, b) => [`三次测量值是 ${a + b}、${a + b * 2}、${a + b * 3}，平均值是多少？`, a + 2 * b, '三次数据相加后除以 3。']]
        ],
        [
            ['二次函数顶点', (a, b) => [`抛物线 y = ${b + 1}(x − ${a})² + ${a + b} 的顶点纵坐标是多少？`, a + b, '顶点处平方项等于 0，纵坐标就是常数项。']],
            ['反比例函数', (a, b) => [`反比例函数经过点 (${a + 12}, ${b + 3})，比例系数是多少？`, (a + 12) * (b + 3), '反比例函数的比例系数等于横坐标乘纵坐标。']],
            ['相似三角形面积', (a, b) => [`两个相似三角形的边长比为 1∶${b + 2}，较小面积为 ${a + 5}，较大面积是多少？`, (a + 5) * (b + 2) ** 2, '面积比等于边长比的平方。']],
            ['简单概率', (a, b) => [`袋中有 ${a + 3} 枚红棋子和 ${b + 3} 枚黑棋子，随机取一枚。取到红棋子的概率写成分数，未约分的分母是多少？`, a + b + 6, '等可能抽取时，未约分的分母是棋子的总枚数。']]
        ]
    ];
    skills.forEach((topics, index) => {
        topics.forEach(([topic, exercise]) => {
            for (let a = 1; a <= 10; a++) {
                for (let b = 1; b <= 11; b++) {
                    // Keep multiplication/division within the table in grade two.
                    if (index === 1 && (topic === '乘法应用' || topic === '平均分') && (a > 9 || b > 9)) continue;
                    if (index === 0 && a + b > 20 || index === 1 && topic === '人民币计算' && a + b > 20) continue;
                    const [stem, answer, tip] = exercise(a, b);
                    add(index + 1, 0, '数学', topic, stem, answer, [answer + 1, answer + 2, answer + 3], tip);
                }
            }
        });
    });

    for (const symbol of ['●', '■', '▲', '◆', '★', '♥']) {
        for (let count = 1; count <= 6; count++) {
            const row = Array(count).fill(symbol).join(' ');
            const options = [1, 2, 3, 4, 5, 6].filter(number => number !== count).slice(0, 3);
            add(0, 0, '数学', '一一对应', `每个图形配一张卡片，需要几张？\n${row}`,
                count, options, `一个图形配一张卡片，有 ${count} 个图形，就需要 ${count} 张卡片。`, 1);
        }
    }
    for (let count = 1; count <= 7; count++) {
        for (const item of ['杯子', '勺子', '积木', '纸船', '贴纸', '气球', '小旗', '玩具车', '蜡笔', '糖果']) {
            const answer = count + 1;
            add(0, 0, '数学', '数序', `数${item}时，已经数到 ${count}，再数一个是几？`,
                answer, [count, count + 2, count + 3], `顺着数，每数一个就加 1。`, 1);
        }
    }
};
